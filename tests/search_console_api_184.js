'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const js=fs.readFileSync(__dirname+'/../public/assets/js/integrations-admin.js','utf8');
const make=(id,extra={})=>Object.assign({id,hidden:false,listeners:{},dataset:{},setAttribute(){},classList:{toggle(){}},addEventListener(name,cb){this.listeners[name]=cb;},querySelector(){return null;}},extra);
const sections=['google','diagnostico','paginas','catalogo'].map(id=>make(id));
const tabs=sections.map(section=>make('button-'+section.id,{dataset:{intTarget:section.id}}));
const submit=make('submit',{disabled:false,textContent:'Consultar dados reais'});
const wait=make('wait',{hidden:true});
const form=make('form',{querySelector(s){return s==='button[type=submit]'?submit:s==='[data-search-console-wait]'?wait:null;}});
const nav={querySelectorAll(){return tabs;}};
const hub={querySelector(sel){return sel==='[data-integrations-nav]'?nav:null;},querySelectorAll(sel){return sel==='[data-int-section]'?sections:sel==='[data-search-console-test-form]'?[form]:[];},contains(){return true;}};
const ctx={document:{getElementById(id){return id==='integrations-hub'?hub:sections.find(x=>x.id===id);}},location:{hash:''},window:{addEventListener(){}},history:{replaceState(){}},navigator:{},decodeURIComponent,encodeURIComponent};
vm.runInNewContext(js,ctx);
assert.equal(typeof form.listeners.submit,'function');form.listeners.submit();assert.equal(submit.disabled,true);assert.equal(wait.hidden,false);assert.match(submit.textContent,/Consultando/);
console.log('Search Console 1.0.84: indicador manual de consulta JavaScript aprovado.');
