'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const markup=fs.readFileSync(root+'/app/bus_admin/view_routes.php','utf8');
const js=fs.readFileSync(root+'/public/assets/js/admin-ui.js','utf8');
assert.match(markup,/<form[^>]*action="\/admin\.php\?action=bus_import_teixeira"[^>]*>/);
assert.match(markup,/<button type="submit"[^>]*data-confirm="Cadastrar os horários da Teixeira/);
assert.doesNotMatch(markup,/<form[^>]*data-confirm="Cadastrar os horários da Teixeira/);
assert.match(js,/btn\.tagName === 'FORM'/,'clicar no checkbox não pede confirmação');
assert.match(js,/document\.addEventListener\('submit', async e =>/,'formulários com data-confirm também são suportados');
assert.match(js,/form\.requestSubmit\(submitter \|\| undefined\)/,'envio nativo válido após autorização');
assert.match(markup,/name="teixeira_confirm" value="1" required/,'checkbox de aprovação obrigatório');
console.log('Teixeira 206 JS: confirmação no submit, clique nativo e autorização antes do POST OK.');
