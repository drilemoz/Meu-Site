'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.join(__dirname,'..');
const {seoAudit}=require('../public/assets/js/seo-audit.js');
const base={title:'Nova obra pública beneficia moradores de Iguatama',seo_title:'',summary:'A prefeitura anunciou uma obra no centro da cidade, conforme informações divulgadas oficialmente.',seo_description:'A prefeitura anunciou uma obra no centro da cidade, conforme informações divulgadas oficialmente.',slug:'obra-no-centro-de-iguatama',body:'Dados confirmados sobre a obra, prazos e locais. '.repeat(4),image:true,cover_alt:'Vista do centro da cidade de Iguatama',image_caption:'Foto ilustrativa da região central da cidade'};
assert.equal(seoAudit(base).score,100);
assert.equal(seoAudit({...base,image:false,cover_alt:'',image_caption:''}).score,80);
assert.equal(seoAudit({...base,slug:'../../config.php'}).score,85);
assert.equal(seoAudit({...base,body:'',has_blocks:true}).score,100);
assert.equal(seoAudit({...base,seo_title:'Í'.repeat(100)}).checks[0].ok,false);
assert.equal(seoAudit({...base,summary:'',seo_description:'Curta',body:''}).checks[3].ok,false);
const view=require('./support/news_editor_view_source.js')();
assert.match(view,/id="news-seo-audit"/);
assert.equal((view.match(/data-tab="/g)||[]).length,9);
assert.match(view,/seo-audit\.js/);
const js=fs.readFileSync(path.join(root,'public/assets/js/seo-audit.js'),'utf8');
assert.match(js,/textContent=/,'resultados de fontes variáveis não devem ser injetados como HTML');
console.log('Central SEO: regras JS, limites, interface e integração do editor aprovados.');
