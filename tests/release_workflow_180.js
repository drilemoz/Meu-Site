// Contratos do workflow de publicação, sem banco nem API remota.
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.join(__dirname,'..');
const yml=fs.readFileSync(path.join(root,'.github/workflows/integration-mariadb.yml'),'utf8');
const ver=fs.readFileSync(path.join(root,'VERSION'),'utf8').trim();
assert.match(ver,/^\d+\.\d+\.\d+$/);
assert.match(yml,/push:\s*\n\s*branches: \[main\]/);
assert.match(yml,/      - 'VERSION'/);
assert.match(yml,/  publicar_release:/);
assert.match(yml,/needs: integration/);
assert.match(yml,/fetch-depth: 2/);
assert.match(yml,/git show HEAD\^:VERSION/);
assert.match(yml,/if: github\.event_name == 'push' && github\.ref == 'refs\/heads\/main'/);
assert.match(yml,/permissions:\s*\n\s*contents: write/);
assert.match(yml,/gh release create \"?\$TAG/);
assert.match(yml,/tools\/build_update_package\.py/);
assert.match(yml,/--notes-file RELEASE_NOTES\.md/);
assert.match(yml,/--target \"?\$GITHUB_SHA/);
assert.match(yml,/if grep -Fxq/);
assert.match(yml,/hashlib\.sha256/);
assert.doesNotMatch(yml,/pull_request_target:/);
console.log('OK workflow v'+ver+': CI obrigatoria, publicacao so em main, release idempotente');
